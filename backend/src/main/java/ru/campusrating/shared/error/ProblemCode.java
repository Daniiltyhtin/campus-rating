package ru.campusrating.shared.error;

public enum ProblemCode {
    UNAUTHENTICATED(401), INVALID_CREDENTIALS(401), FORBIDDEN(403), GROUP_NOT_ACCESSIBLE(403),
    PASSWORD_CHANGE_REQUIRED(403), EMAIL_NOT_VERIFIED(403), CSRF_INVALID(403), NOT_FOUND(404),
    INVALID_STATE(409), EMAIL_TAKEN(409), EMAIL_RESERVED_FOR_TEACHER(409), ALREADY_CONFIRMED(409),
    VALIDATION_FAILED(400), PASSWORD_REUSED(400), FILE_TOO_LARGE(413), FILE_TYPE_NOT_ALLOWED(415),
    BUDGET_EXCEEDED(422), NOT_ENROLLED(422), STUDENT_NOT_ELIGIBLE(422), MEMBERSHIP_NOT_ACTIVE(422),
    ENROLLMENT_CLOSED(422);

    private final int status;

    ProblemCode(int status) { this.status = status; }

    public int status() { return status; }
}
