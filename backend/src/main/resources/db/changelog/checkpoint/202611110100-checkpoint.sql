CREATE TABLE checkpoint (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id bigint NOT NULL REFERENCES app_user(id),
    title varchar(200) NOT NULL CHECK (length(trim(title)) > 0),
    description varchar(10000) NOT NULL,
    deadline timestamptz NOT NULL,
    cost integer NOT NULL CHECK (cost BETWEEN 1 AND 1000),
    penalty_step integer NOT NULL CHECK (penalty_step > 0),
    penalty_interval_seconds integer NOT NULL CHECK (penalty_interval_seconds > 0),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE INDEX checkpoint_author_deadline_idx ON checkpoint (author_id, deadline, id);
CREATE INDEX checkpoint_deadline_idx ON checkpoint (deadline, id);
CREATE TABLE checkpoint_group (
    checkpoint_id bigint NOT NULL REFERENCES checkpoint(id),
    group_id bigint NOT NULL REFERENCES study_group(id),
    PRIMARY KEY (checkpoint_id, group_id)
);
CREATE INDEX checkpoint_group_group_idx ON checkpoint_group (group_id, checkpoint_id);
CREATE TABLE assignment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checkpoint_id bigint NOT NULL REFERENCES checkpoint(id),
    student_id bigint NOT NULL REFERENCES app_user(id),
    group_id bigint NOT NULL REFERENCES study_group(id),
    student_full_name text NOT NULL,
    state text NOT NULL CHECK (state IN ('OPEN', 'SUBMITTED', 'ACCEPTED')),
    charged integer NOT NULL DEFAULT 0 CHECK (charged >= 0),
    last_penalty_slot integer CHECK (last_penalty_slot >= 0),
    accepted_at timestamptz,
    created_at timestamptz NOT NULL,
    UNIQUE (checkpoint_id, student_id)
);
CREATE INDEX assignment_state_checkpoint_idx ON assignment (state, checkpoint_id);
CREATE INDEX assignment_checkpoint_name_idx ON assignment (checkpoint_id, student_full_name, id);
CREATE INDEX assignment_student_idx ON assignment (student_id, state, id);
CREATE TABLE submission (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id bigint NOT NULL REFERENCES assignment(id),
    kind text NOT NULL CHECK (kind IN ('LINK', 'FILE')),
    url text,
    file_key text,
    file_name text,
    size_bytes bigint CHECK (size_bytes >= 0),
    content_type text,
    submitted_at timestamptz NOT NULL,
    return_comment text,
    returned_at timestamptz,
    CHECK ((kind = 'LINK' AND url IS NOT NULL AND file_key IS NULL AND file_name IS NULL
            AND size_bytes IS NULL AND content_type IS NULL)
        OR (kind = 'FILE' AND url IS NULL AND file_key IS NOT NULL AND file_name IS NOT NULL
            AND size_bytes IS NOT NULL AND content_type IS NOT NULL))
);
CREATE INDEX submission_assignment_time_idx ON submission (assignment_id, submitted_at DESC, id DESC);
