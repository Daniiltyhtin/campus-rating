CREATE TABLE user_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id bigint NOT NULL,
    kind text NOT NULL CHECK (kind IN ('ASSIGNMENT_CREATED', 'DEADLINE_REMINDER', 'WORK_ACCEPTED', 'WORK_RETURNED',
        'POINTS_AWARDED', 'ACTIVITY_CREATED', 'WORK_SUBMITTED')),
    dedup_key text NOT NULL,
    created_at timestamptz NOT NULL,
    target_id bigint NOT NULL,
    title text NOT NULL,
    deadline timestamptz,
    amount integer CHECK (amount > 0),
    currency text CHECK (currency IN ('BUA', 'BOA')),
    student_full_name text,
    UNIQUE (recipient_id, dedup_key)
);
CREATE INDEX user_event_recipient_time_idx ON user_event (recipient_id, created_at DESC, id DESC);
