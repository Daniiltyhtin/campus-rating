CREATE TABLE app_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL,
    role text NOT NULL CHECK (role IN ('STUDENT', 'TEACHER', 'ADMIN')),
    full_name text NOT NULL
);
CREATE UNIQUE INDEX app_user_email_unique ON app_user (lower(email));
CREATE TABLE group_membership (
    student_id bigint PRIMARY KEY REFERENCES app_user(id),
    group_id bigint NOT NULL REFERENCES study_group(id),
    state text NOT NULL CHECK (state IN ('PENDING', 'ACTIVE')),
    activated_at timestamptz,
    CHECK ((state = 'ACTIVE' AND activated_at IS NOT NULL)
        OR (state = 'PENDING' AND activated_at IS NULL))
);
CREATE INDEX group_membership_group_idx ON group_membership (group_id, state);
