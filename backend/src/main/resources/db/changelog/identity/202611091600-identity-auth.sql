ALTER TABLE app_user ADD COLUMN password_hash text;
ALTER TABLE app_user ADD COLUMN must_change_password boolean NOT NULL DEFAULT false;
ALTER TABLE app_user ADD COLUMN department_id bigint REFERENCES department(id);

CREATE TABLE teacher_allowlist (
    email text NOT NULL,
    department_id bigint NOT NULL REFERENCES department(id)
);
CREATE UNIQUE INDEX teacher_allowlist_email_unique ON teacher_allowlist(lower(email));
CREATE TABLE teacher_approval (
    teacher_id bigint PRIMARY KEY REFERENCES app_user(id),
    approved_by bigint REFERENCES app_user(id),
    approved_at timestamptz NOT NULL
);
CREATE TABLE teacher_grant (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id bigint NOT NULL REFERENCES app_user(id),
    kind text NOT NULL,
    group_id bigint REFERENCES study_group(id),
    faculty_id bigint REFERENCES faculty(id),
    course integer,
    CHECK (
        (kind = 'GROUP' AND group_id IS NOT NULL AND faculty_id IS NULL AND course IS NULL)
        OR (kind = 'FACULTY' AND group_id IS NULL AND faculty_id IS NOT NULL AND course IS NULL)
        OR (kind = 'FACULTY_COURSE' AND group_id IS NULL AND faculty_id IS NOT NULL AND course IS NOT NULL AND course BETWEEN 1 AND 6)
        OR (kind = 'COURSE' AND group_id IS NULL AND faculty_id IS NULL AND course IS NOT NULL AND course BETWEEN 1 AND 6)
    )
);
CREATE INDEX teacher_grant_teacher_idx ON teacher_grant(teacher_id);
