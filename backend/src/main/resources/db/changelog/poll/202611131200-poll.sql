CREATE TABLE poll (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id bigint NOT NULL REFERENCES app_user(id),
    title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
    description text NOT NULL CHECK (char_length(description) <= 2000),
    ends_at timestamptz NOT NULL,
    anonymous boolean NOT NULL,
    created_at timestamptz NOT NULL,
    closed_at timestamptz
);
CREATE INDEX poll_author_idx ON poll (author_id);
CREATE INDEX poll_closing_idx ON poll (ends_at) WHERE closed_at IS NULL;
CREATE TABLE poll_group (
    poll_id bigint NOT NULL REFERENCES poll(id),
    group_id bigint NOT NULL REFERENCES study_group(id),
    PRIMARY KEY (poll_id, group_id)
);
CREATE INDEX poll_group_group_idx ON poll_group (group_id);
CREATE TABLE poll_question (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id bigint NOT NULL REFERENCES poll(id),
    position integer NOT NULL,
    text text NOT NULL CHECK (char_length(text) BETWEEN 1 AND 500),
    type text NOT NULL CHECK (type IN ('SINGLE', 'MULTIPLE')),
    UNIQUE (poll_id, position)
);
CREATE TABLE poll_option (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id bigint NOT NULL REFERENCES poll_question(id),
    position integer NOT NULL,
    text text NOT NULL CHECK (char_length(text) BETWEEN 1 AND 200),
    vote_count integer NOT NULL DEFAULT 0 CHECK (vote_count >= 0),
    UNIQUE (question_id, position)
);
CREATE TABLE poll_participation (
    poll_id bigint NOT NULL REFERENCES poll(id),
    student_id bigint NOT NULL REFERENCES app_user(id),
    voted_at timestamptz NOT NULL,
    PRIMARY KEY (poll_id, student_id)
);
CREATE TABLE poll_named_choice (
    poll_id bigint NOT NULL REFERENCES poll(id),
    option_id bigint NOT NULL REFERENCES poll_option(id),
    student_id bigint NOT NULL REFERENCES app_user(id),
    PRIMARY KEY (poll_id, option_id, student_id)
);
