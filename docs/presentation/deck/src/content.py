X, W = 120, 1680          # поля и ширина контента
TOP = 176                 # начало контента под шапкой слайда


def kicker(text, y=TOP, x=X, w=W):
    return {'t': 'text', 'x': x, 'y': y, 'w': w, 'h': 34, 'st': 'kicker', 'c': 'accent', 'text': text}


def title(text, y=TOP + 46, h=170, w=1500, st='h2'):
    return {'t': 'text', 'x': X, 'y': y, 'w': w, 'h': h, 'st': st, 'c': 'fg', 'text': text}


def text(x, y, w, h, s, st='body', c='fg', **kw):
    d = {'t': 'text', 'x': x, 'y': y, 'w': w, 'h': h, 'st': st, 'c': c, 'text': s}
    d.update(kw)
    return d


def card(x, y, w, h):
    return {'t': 'card', 'x': x, 'y': y, 'w': w, 'h': h}


def rule(x, y, w, c='rule', weight=2):
    return {'t': 'rule', 'x': x, 'y': y, 'w': w, 'c': c, 'weight': weight}


def img(x, y, w, h, src, frame=True):
    return {'t': 'img', 'x': x, 'y': y, 'w': w, 'h': h, 'src': src, 'frame': frame}


def cards_row(y, h, items, gap=32, x=X, w=W, title_h=96, label=True):
    """items: (метка, заголовок, текст[, цвет метки])"""
    n = len(items)
    cw = (w - gap * (n - 1)) / n
    out = []
    for i, it in enumerate(items):
        cx = x + i * (cw + gap)
        out.append(card(cx, y, cw, h))
        yy = y + 36
        if label and it[0]:
            out.append(text(cx + 36, yy, cw - 72, 34, it[0], 'kicker', it[3] if len(it) > 3 else 'accent'))
            yy += 52
        out.append(text(cx + 36, yy, cw - 72, title_h, it[1], 'h3'))
        out.append(text(cx + 36, yy + title_h + 12, cw - 72, h - (yy - y) - title_h - 48, it[2], 'body', 'muted'))
    return out


def stats_row(y, items, x=X, w=W, gap=40, h=210):
    """items: (число, подпись[, цвет])"""
    n = len(items)
    cw = (w - gap * (n - 1)) / n
    out = []
    for i, it in enumerate(items):
        cx = x + i * (cw + gap)
        out.append(rule(cx, y, cw, 'fg', 3))
        out.append(text(cx, y + 20, cw, 136, it[0], 'stat', it[2] if len(it) > 2 else 'accent'))
        out.append(text(cx, y + 162, cw, h - 162 + 20, it[1], 'small', 'muted'))
    return out


def steps(y, items, x=X, w=W, gap=28, h=260, num_c='accent', start=1):
    """items: (заголовок, текст) — пронумерованный процесс слева направо"""
    n = len(items)
    cw = (w - gap * (n - 1)) / n
    out = []
    for i, (t, s) in enumerate(items):
        cx = x + i * (cw + gap)
        out.append(rule(cx, y, cw, 'accent', 3))
        out.append(text(cx, y + 22, cw, 50, f'{i + start:02d}', 'mono', num_c))
        out.append(text(cx, y + 78, cw, 84, t, 'h4'))
        out.append(text(cx, y + 170, cw, h - 170, s, 'small', 'muted'))
    return out


def bullets(x, y, w, h, items, st='lead'):
    return text(x, y, w, h, '\n'.join(items), st, 'fg', bullets=True)


