import { readFile, mkdir, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';
import ts from 'typescript';

const source = new URL('../../docs/spec/api/openapi.yaml', import.meta.url);
const schema = parse(await readFile(source, 'utf8'));
const methods = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options']);
function resolve(value) {
  if (Array.isArray(value)) return value.map(resolve);
  if (!value || typeof value !== 'object') return value;
  if (value.$ref) {
    if (!value.$ref.startsWith('#/')) throw new Error('Only local example references are supported');
    const target = value.$ref.slice(2).split('/').reduce((node, key) => node[key.replace(/~1/g, '/').replace(/~0/g, '~')], schema);
    if (target === undefined) throw new Error(`Unresolved example ${value.$ref}`);
    return resolve(target);
  }
  return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, resolve(item)]));
}
const examples = [];
for (const [path, pathItem] of Object.entries(schema.paths)) {
  for (const [method, operation] of Object.entries(pathItem)) {
    if (!methods.has(method)) continue;
    const responses = [];
    for (const [status, rawResponse] of Object.entries(operation.responses)) {
      if (!/^2\d\d$/.test(status)) continue;
      const response = rawResponse.$ref ? resolve(rawResponse) : rawResponse;
      const media = Object.entries(response.content ?? {})[0];
      const values = {};
      if (media) {
        if (Object.hasOwn(media[1], 'example')) values.default = resolve(media[1].example);
        for (const [key, example] of Object.entries(media[1].examples ?? {})) values[key] = resolve(example).value;
        const entries = Object.entries(values);
        if (entries.length === 1) {
          const [name, value] = entries[0];
          if (value && Array.isArray(value.items) && typeof value.nextCursor === 'string') {
            const split = Math.max(1, Math.ceil(value.items.length / 2));
            delete values[name];
            values.page1 = { ...value, items: value.items.slice(0, split) };
            values.page2 = { ...value, items: value.items.slice(split), nextCursor: null };
          }
        }
        if (!Object.keys(values).length && !media[0].includes('octet-stream')) throw new Error(`Missing example: ${method} ${path} ${status}`);
      }
      responses.push({ status: Number(status), ...(media ? { mediaType: media[0] } : {}), examples: values });
    }
    examples.push({ method: method.toUpperCase(), path, operationId: operation.operationId, responses });
  }
}
const apiDir = new URL('../src/api/', import.meta.url);
const mockDir = new URL('../src/mocks/', import.meta.url);
await mkdir(apiDir, { recursive: true });
await mkdir(mockDir, { recursive: true });
const types = astToString(await openapiTS(source, {
  transform(schemaObject) {
    if (schemaObject.format === 'binary') return ts.factory.createTypeReferenceNode('Blob');
  },
}));
const mocks =
  '// Generated by npm run api:gen. Do not edit.\n' +
  'export interface MockOperation { method: string; path: string; operationId: string; responses: { status: number; mediaType?: string; examples: Record<string, unknown> }[] }\n' +
  `export const examples: readonly MockOperation[] = ${JSON.stringify(examples, null, 2)};\n`;
for (const [file, contents] of [[new URL('schema.d.ts', apiDir), types], [new URL('examples.generated.ts', mockDir), mocks]]) {
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== contents) throw new Error(`Generated file is stale: ${file.pathname}`);
  } else await writeFile(file, contents, 'utf8');
}
