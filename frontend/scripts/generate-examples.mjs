import { readFile, writeFile } from 'node:fs/promises';
import { parse } from 'yaml';
import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

const contractUrl = new URL('../../docs/spec/api/openapi.yaml', import.meta.url);
const ast = await openapiTS(contractUrl, {
  transform(schema) {
    if (schema.type === 'string' && schema.format === 'binary') return ts.factory.createTypeReferenceNode('Blob');
  },
});
await writeFile(new URL('../src/api/schema.d.ts', import.meta.url), '// Generated by npm run api:gen. Do not edit.\n' + astToString(ast));

const contract = parse(await readFile(new URL('../../docs/spec/api/openapi.yaml', import.meta.url), 'utf8'));
const methods = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace']);
function resolve(value) {
  if (Array.isArray(value)) return value.map(resolve);
  if (!value || typeof value !== 'object') return value;
  if (value.$ref) {
    if (!value.$ref.startsWith('#/')) throw new Error(`External example reference: ${value.$ref}`);
    const target = value.$ref.slice(2).split('/').reduce((node, key) => node[key.replaceAll('~1', '/').replaceAll('~0', '~')], contract);
    if (target === undefined) throw new Error(`Missing example reference: ${value.$ref}`);
    return resolve(target);
  }
  return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, resolve(child)]));
}
const examples = [];
for (const [path, item] of Object.entries(contract.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!methods.has(method)) continue;
    const responses = [];
    for (const [status, raw] of Object.entries(operation.responses)) {
      const response = raw.$ref ? resolve(raw) : raw;
      for (const [contentType, media] of Object.entries(response.content ?? {})) {
        const values = media.schema?.format === 'binary' ? [''] : media.example !== undefined ? [resolve(media.example)] : Object.values(media.examples ?? {}).map((example) => resolve(example).value);
        for (const body of values) responses.push({ status: Number(status), contentType, body });
      }
      if (!response.content && /^2\d\d$/.test(status)) responses.push({ status: Number(status), contentType: '', body: null });
    }
    if (!responses.some(({ status }) => status >= 200 && status < 300)) throw new Error(`No success example for ${operation.operationId}`);
    examples.push({ path, method, operationId: operation.operationId, responses });
  }
}
await writeFile(new URL('../src/mocks/examples.generated.ts', import.meta.url),
  '// Generated by npm run api:gen. Do not edit.\n' +
  'export interface ExampleOperation { path: string; method: string; operationId: string; responses: { status: number; contentType: string; body: unknown }[] }\n' +
  `export const examples: ExampleOperation[] = ${JSON.stringify(examples, null, 2)};\n`);

await writeFile(new URL('../src/api/problemCodes.generated.ts', import.meta.url),
  '// Generated by npm run api:gen. Do not edit.\n' +
  `export const problemCodes = ${JSON.stringify(contract.components.schemas.ProblemCode.enum)} as const;\n`);
