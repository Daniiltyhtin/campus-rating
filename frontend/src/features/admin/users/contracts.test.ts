import { describe, expect, it } from 'vitest';
import { requestsTitle } from './contracts';

describe('requestsTitle', () => {
  it.each([
    [1, '1 заявка преподавателя ждёт решения'],
    [2, '2 заявки преподавателей ждут решения'],
    [4, '4 заявки преподавателей ждут решения'],
    [5, '5 заявок преподавателей ждут решения'],
    [11, '11 заявок преподавателей ждут решения'],
    [14, '14 заявок преподавателей ждут решения'],
    [21, '21 заявка преподавателя ждёт решения'],
    [22, '22 заявки преподавателей ждут решения'],
  ])('%i', (count, text) => expect(requestsTitle(count)).toBe(text));
});
